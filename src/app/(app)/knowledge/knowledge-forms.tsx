"use client";

import { FileText, Search, ShieldAlert, Sparkles } from "lucide-react";
import { useActionState, useEffect, useRef } from "react";
import { AiBadge, FormMessage } from "@/components/app-ui";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { NativeSelect, NativeSelectOption } from "@/components/ui/native-select";
import { idleState } from "@/lib/action-state";
import {
  askAction,
  deleteDocumentAction,
  reindexDocumentAction,
  uploadDocumentAction,
} from "./actions";
import { idleAskState, type AskSource, type AskState } from "./ask-state";

export function AskForm() {
  const [state, formAction, pending] = useActionState(askAction, idleAskState);
  const question = state.status === "idle" ? "" : (state.question ?? "");

  return (
    <div className="flex flex-col gap-4">
      <form action={formAction} className="flex flex-col gap-2 sm:flex-row" role="search">
        <Label htmlFor="question" className="sr-only">
          Question
        </Label>
        <Input
          id="question"
          name="question"
          placeholder="e.g. How do I refund a duplicate charge?"
          defaultValue={question}
          key={question}
          maxLength={1000}
          required
        />
        <Button type="submit" disabled={pending}>
          <Search aria-hidden />
          {pending ? "Searching…" : "Ask"}
        </Button>
      </form>

      {state.status === "error" && <FormMessage>{state.message}</FormMessage>}
      {state.status === "done" && <AskResult state={state} />}
    </div>
  );
}

function AskResult({ state }: { state: Extract<AskState, { status: "done" }> }) {
  if (state.mode === "search_only") {
    return (
      <div className="flex flex-col gap-3" aria-live="polite">
        <p className="text-sm text-muted-foreground">
          AI answers are off (no Claude API key), so here are the most relevant sections from the
          knowledge base.
        </p>
        {state.sources.length === 0 ? (
          <p className="text-sm">No matching sections. Try different words.</p>
        ) : (
          <SourceList sources={state.sources} />
        )}
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-4" aria-live="polite">
      <div className="rounded-xl border p-4">
        <div className="mb-2 flex flex-wrap items-center gap-2">
          <Sparkles className="size-4 text-muted-foreground" aria-hidden />
          <span className="text-sm font-medium">Answer</span>
          <AiBadge />
          {!state.grounded && (
            <Badge variant="secondary" className="gap-1">
              <ShieldAlert aria-hidden />
              Not fully covered by the knowledge base
            </Badge>
          )}
        </div>
        <p className="text-sm whitespace-pre-wrap">{withCitationLinks(state.answer ?? "")}</p>
        {state.model && (
          <p className="mt-3 text-xs text-muted-foreground">
            Generated by {state.model} from the sources below. Check before sharing with a customer.
          </p>
        )}
      </div>
      {state.sources.length > 0 && <SourceList sources={state.sources} />}
    </div>
  );
}

/** Turns "[2]" markers into links to the matching source. Everything else stays plain text. */
function withCitationLinks(text: string) {
  return text.split(/(\[\d+\])/g).map((part, i) => {
    const n = /^\[(\d+)\]$/.exec(part)?.[1];
    return n ? (
      <a key={i} href={`#source-${n}`} className="font-medium text-primary hover:underline">
        {part}
      </a>
    ) : (
      part
    );
  });
}

function SourceList({ sources }: { sources: AskSource[] }) {
  return (
    <ol className="flex flex-col gap-2">
      {sources.map((s) => (
        <li key={s.n} id={`source-${s.n}`} className="rounded-lg border bg-muted/30 p-3 text-sm">
          <div className="mb-1 flex flex-wrap items-center gap-2">
            <span className="font-medium">[{s.n}]</span>
            <FileText className="size-4 text-muted-foreground" aria-hidden />
            <span className="font-medium">{s.documentTitle}</span>
            {s.kind === "runbook" && <Badge variant="outline">Internal runbook</Badge>}
            <span className="text-xs text-muted-foreground">
              relevance {Math.round(s.score * 100)}%
            </span>
          </div>
          <p className="line-clamp-6 whitespace-pre-wrap text-muted-foreground">{s.content}</p>
        </li>
      ))}
    </ol>
  );
}

export function UploadForm({ maxMb }: { maxMb: number }) {
  const [state, formAction, pending] = useActionState(uploadDocumentAction, idleState);
  const formRef = useRef<HTMLFormElement>(null);

  useEffect(() => {
    if (state.status === "success") formRef.current?.reset();
  }, [state]);

  return (
    <form ref={formRef} action={formAction} className="flex flex-col gap-4">
      {state.message && (
        <FormMessage tone={state.status === "success" ? "success" : "error"}>
          {state.message}
        </FormMessage>
      )}
      <div className="grid gap-4 sm:grid-cols-3">
        <div className="flex flex-col gap-1.5 sm:col-span-2">
          <Label htmlFor="doc-file">File (.md, .txt, .pdf or .docx, up to {maxMb} MB)</Label>
          <Input
            id="doc-file"
            name="file"
            type="file"
            accept=".md,.markdown,.txt,.pdf,.docx,text/markdown,text/plain,application/pdf,application/vnd.openxmlformats-officedocument.wordprocessingml.document"
            required
          />
        </div>
        <div className="flex flex-col gap-1.5">
          <Label htmlFor="doc-kind">Type</Label>
          <NativeSelect id="doc-kind" name="kind" defaultValue="article" className="w-full">
            <NativeSelectOption value="article">Help article (can be shared)</NativeSelectOption>
            <NativeSelectOption value="runbook">Internal runbook</NativeSelectOption>
          </NativeSelect>
        </div>
        <div className="flex flex-col gap-1.5 sm:col-span-3">
          <Label htmlFor="doc-title">Title (optional)</Label>
          <Input
            id="doc-title"
            name="title"
            maxLength={200}
            placeholder="Defaults to the first # heading, or the file name"
          />
        </div>
      </div>
      <div>
        <Button type="submit" disabled={pending}>
          {pending ? "Uploading and indexing…" : "Upload"}
        </Button>
      </div>
    </form>
  );
}

export function DocumentRowActions({
  documentId,
  title,
  canReindex,
}: {
  documentId: string;
  title: string;
  canReindex: boolean;
}) {
  return (
    <div className="flex justify-end gap-2">
      {canReindex && (
        <form action={reindexDocumentAction}>
          <input type="hidden" name="documentId" value={documentId} />
          <Button type="submit" variant="outline" size="sm">
            Re-index
          </Button>
        </form>
      )}
      <form
        action={deleteDocumentAction}
        onSubmit={(e) => {
          if (!confirm(`Delete "${title}"? Answers will no longer use it.`)) e.preventDefault();
        }}
      >
        <input type="hidden" name="documentId" value={documentId} />
        <Button type="submit" variant="ghost" size="sm" className="text-destructive">
          Delete
        </Button>
      </form>
    </div>
  );
}
